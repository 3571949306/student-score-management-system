CREATE DATABASE IF NOT EXISTS spring_security_demo DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE spring_security_demo;

DROP TABLE IF EXISTS student_score;
DROP TABLE IF EXISTS sys_user_role;
DROP TABLE IF EXISTS sys_role;
DROP TABLE IF EXISTS sys_user;

CREATE TABLE sys_user (
    id BIGINT NOT NULL AUTO_INCREMENT,
    username VARCHAR(50) NOT NULL,
    password VARCHAR(100) NOT NULL,
    enabled TINYINT(1) NOT NULL DEFAULT 1,
    PRIMARY KEY (id),
    UNIQUE KEY uk_sys_user_username (username)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE sys_role (
    id BIGINT NOT NULL AUTO_INCREMENT,
    name VARCHAR(50) NOT NULL,
    description VARCHAR(100),
    PRIMARY KEY (id),
    UNIQUE KEY uk_sys_role_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE sys_user_role (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_role_user FOREIGN KEY (user_id) REFERENCES sys_user (id),
    CONSTRAINT fk_user_role_role FOREIGN KEY (role_id) REFERENCES sys_role (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE student_score (
    id BIGINT NOT NULL AUTO_INCREMENT,
    student_name VARCHAR(50) NOT NULL,
    student_number VARCHAR(30) NOT NULL,
    class_name VARCHAR(30) NOT NULL,
    subject VARCHAR(30) NOT NULL,
    score DECIMAL(5,2) NOT NULL,
    exam_name VARCHAR(50),
    semester VARCHAR(30),
    exam_date DATE,
    remark VARCHAR(200),
    PRIMARY KEY (id),
    KEY idx_student_score_class (class_name),
    KEY idx_student_score_student_number (student_number),
    KEY idx_student_score_exam (exam_name, semester)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

